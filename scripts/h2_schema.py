#!/usr/bin/env python3
"""Turns the DBA script db_migrations/01_CREATE_TABLES.sql into an H2 script (Oracle mode) for local testing without Docker.
It also appends the laptop-only HRMS stand-ins: 03_CREATE_HRMS_MOCK_TABLES.sql and 05_LOCAL_TEST_EMPLOYEES.sql (the application
reads employees from those tables exactly as it reads the bank's HRMS tables in UAT).

The tables, columns, checks and foreign keys stay exactly as the DBA script defines them, so testing on H2 also tests that script.
Only the two things H2 cannot do are replaced:
  1. `LOB (...) STORE AS SECUREFILE (...)`   (Oracle storage option)            -> removed
  2. the unique index on a CASE expression   (one open request per project)     -> left out (see the note in the code)
The output starts with DROP TABLE ... lines, so running it again gives a fresh, empty database.

    python3 scripts/h2_schema.py > .run/h2-schema.sql
"""
import os
import re
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sql = open(os.path.join(root, "db_migrations", "01_CREATE_TABLES.sql"), encoding="utf-8").read()

# 1. Oracle-only storage clause after the closing parenthesis of CREATE TABLE project_images
sql, n1 = re.subn(r"\nLOB \(file_data\) STORE AS SECUREFILE \(.*?\)\s*;", ";", sql, flags=re.S)

# 2. function-based unique index (one open request per project): H2 cannot index an expression, and a workaround with a
#    generated column breaks H2 (the column keeps using the session that created it: "database has been closed").
#    So H2 runs WITHOUT this database backstop; the application still checks the rule. Oracle (Docker, UAT, prod) enforces it.
pattern = re.compile(r"CREATE UNIQUE INDEX ux_staging_one_open ON project_staging \(.*?\);", re.S)
sql, n2 = pattern.subn("-- ux_staging_one_open is Oracle-only (H2 cannot index an expression); the application enforces the rule on H2", sql)
if not (n1 == 1 and n2 == 1):
    sys.exit("h2_schema.py: 01_CREATE_TABLES.sql changed shape (SECUREFILE clause or ux_staging_one_open not found); update this script")

# 3. laptop HRMS tables + test employees (plain SQL that H2 in Oracle mode understands)
hrms = open(os.path.join(root, "db_migrations", "03_CREATE_HRMS_MOCK_TABLES.sql"), encoding="utf-8").read()
hrms += "\n" + open(os.path.join(root, "db_migrations", "05_LOCAL_TEST_EMPLOYEES.sql"), encoding="utf-8").read()
sql += "\n" + hrms

# SQL*Plus-only commands (PROMPT, SET ...) mean nothing to H2
sql = re.sub(r"^(PROMPT|SET|WHENEVER|SPOOL)\b.*$", "", sql, flags=re.M | re.I)

tables = re.findall(r"^CREATE TABLE (\w+)", sql, flags=re.M | re.I)
drops = "".join(f"DROP TABLE IF EXISTS {t} CASCADE;\n" for t in reversed(tables))
sys.stdout.write("-- generated by scripts/h2_schema.py from db_migrations/01_CREATE_TABLES.sql (do not edit)\n" + drops + "\n" + sql)

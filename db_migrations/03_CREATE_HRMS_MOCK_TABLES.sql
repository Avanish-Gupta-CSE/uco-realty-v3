-- ============================================================================

-- 1. Employee Contact Details Table
CREATE TABLE HRMS_DBA.EMPLOYEE_CONTACT_DETAILS (
    EMP_ID VARCHAR2(20) NOT NULL PRIMARY KEY,
    EMP_NAME VARCHAR2(100) NOT NULL,
    SOL_ID VARCHAR2(10) NOT NULL,
    SOL_DESC VARCHAR2(150),
    MOBILE_NO VARCHAR2(20),
    EMAIL_ID VARCHAR2(100)
);

-- 2. Employee Tenure & Posting Details Table
CREATE TABLE HRMS_DBA.EMPLOYEE_TENURE (
    TENURE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMP_ID VARCHAR2(20) NOT NULL,
    SCALE VARCHAR2(20) NOT NULL,
    CADRE VARCHAR2(30) NOT NULL,
    POSTING_REGION_NAME VARCHAR2(100),
    TENURE_AS VARCHAR2(100),
    IS_CURRENT CHAR(1) DEFAULT 'Y' CHECK (IS_CURRENT IN ('Y', 'N')),
    CONSTRAINT FK_TENURE_EMP FOREIGN KEY (EMP_ID) REFERENCES HRMS_DBA.EMPLOYEE_CONTACT_DETAILS(EMP_ID)
);

-- 3. Employee Job Profile Table
CREATE TABLE HRMS_DBA.EMPLOYEE_JOB_PROFILE (
    PROFILE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMP_ID VARCHAR2(20) NOT NULL,
    JOB_PROFILE VARCHAR2(50),
    CONSTRAINT FK_JOB_EMP FOREIGN KEY (EMP_ID) REFERENCES HRMS_DBA.EMPLOYEE_CONTACT_DETAILS(EMP_ID)
);


-- ============================================================================
-- Migration for EXISTING databases: move to the maker-checker STAGING model.
--
--   PROJECTS          now holds only APPROVED records (status APPROVED, or DELETED kept for the logs)
--   PROJECT_STAGING   the maker's working table: new projects, edits, unit reductions and deletions wait here
--                     until a checker approves; then they are applied to PROJECTS
--
-- What this script does (safe to re-run: it does nothing once PROJECT_STAGING exists):
--   1. drops the short-lived PROJECT_CHANGE_REQUESTS design (and project_images.change_request_id) if present
--   2. adds projects.row_version, removes projects.change_state
--   3. creates PROJECT_STAGING (+ indexes, one open request per project)
--   4. project_images: project_id becomes optional, staging_id added (a photo belongs to a project OR to staging)
--   5. MOVES every project that is not yet approved (DRAFT, PENDING_APPROVAL, NEEDS_CORRECTION, REJECTED)
--      from PROJECTS into PROJECT_STAGING as a CREATE request, with its photos
-- ONLY for the developer laptop database created by earlier builds. The bank database is new: it gets all of this
-- from 01_CREATE_TABLES.sql, so the DBA never runs this script.
-- ============================================================================
DECLARE
  n NUMBER;
  PROCEDURE ddl(p_sql VARCHAR2) IS BEGIN EXECUTE IMMEDIATE p_sql; END;
BEGIN
  SELECT COUNT(*) INTO n FROM user_tables WHERE table_name = 'PROJECT_STAGING';
  IF n > 0 THEN
    DBMS_OUTPUT.PUT_LINE('PROJECT_STAGING already exists: nothing to do');
    RETURN;
  END IF;

  -- 1. old change-request design
  SELECT COUNT(*) INTO n FROM user_tab_columns WHERE table_name = 'PROJECT_IMAGES' AND column_name = 'CHANGE_REQUEST_ID';
  IF n > 0 THEN
    ddl('DELETE FROM project_images WHERE change_request_id IS NOT NULL');
    BEGIN ddl('ALTER TABLE project_images DROP CONSTRAINT fk_project_images_change'); EXCEPTION WHEN OTHERS THEN NULL; END;
    ddl('ALTER TABLE project_images DROP COLUMN change_request_id');
  END IF;
  SELECT COUNT(*) INTO n FROM user_tables WHERE table_name = 'PROJECT_CHANGE_REQUESTS';
  IF n > 0 THEN ddl('DROP TABLE project_change_requests CASCADE CONSTRAINTS'); END IF;

  -- 2. projects: optimistic lock column, no change_state any more
  SELECT COUNT(*) INTO n FROM user_tab_columns WHERE table_name = 'PROJECTS' AND column_name = 'ROW_VERSION';
  IF n = 0 THEN ddl('ALTER TABLE projects ADD (row_version NUMBER DEFAULT 0 NOT NULL)'); END IF;
  SELECT COUNT(*) INTO n FROM user_tab_columns WHERE table_name = 'PROJECTS' AND column_name = 'CHANGE_STATE';
  IF n > 0 THEN ddl('ALTER TABLE projects DROP COLUMN change_state'); END IF;
  SELECT COUNT(*) INTO n FROM user_tab_columns WHERE table_name = 'PROJECTS' AND column_name = 'DELETED_AT';
  IF n = 0 THEN ddl('ALTER TABLE projects ADD (deleted_at TIMESTAMP, deleted_by VARCHAR2(50))'); END IF;
  ddl('ALTER TABLE projects MODIFY (status DEFAULT ''APPROVED'', is_published DEFAULT 1)');

  -- 3. staging table
  ddl(q'[CREATE TABLE project_staging (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id VARCHAR2(20) NOT NULL,
  request_type VARCHAR2(10) NOT NULL,
  status VARCHAR2(20) NOT NULL,
  zone_name VARCHAR2(100),
  branch_name VARCHAR2(100),
  state_name VARCHAR2(100),
  city_name VARCHAR2(100),
  project_name VARCHAR2(255),
  rera_no VARCHAR2(100),
  property_id VARCHAR2(100),
  type_of_unit VARCHAR2(100),
  approval_date DATE,
  total_inventory NUMBER,
  unsold_inventory NUMBER,
  inventory_as_on_date DATE,
  amenities CLOB,
  start_date DATE,
  completion_date DATE,
  apt_per_floor NUMBER,
  no_of_towers NUMBER,
  total_project_area VARCHAR2(100),
  carpet_min VARCHAR2(50),
  carpet_max VARCHAR2(50),
  buildup_min VARCHAR2(50),
  buildup_max VARCHAR2(50),
  dist_railway VARCHAR2(100),
  dist_airport VARCHAR2(100),
  avg_rate VARCHAR2(100),
  budget_min VARCHAR2(100),
  budget_max VARCHAR2(100),
  builder_name VARCHAR2(255),
  project_address VARCHAR2(500),
  pin_code VARCHAR2(10),
  promoter1 VARCHAR2(255),
  promoter2 VARCHAR2(255),
  promoter3 VARCHAR2(255),
  promoter4 VARCHAR2(255),
  promoter5 VARCHAR2(255),
  sales_exec_name VARCHAR2(255),
  sales_mobile VARCHAR2(15),
  sales_email VARCHAR2(255),
  website VARCHAR2(255),
  builder_rating VARCHAR2(50),
  builder_bg CLOB,
  branch_head_name VARCHAR2(255),
  branch_head_number VARCHAR2(15),
  rel_exec_name VARCHAR2(255),
  rel_exec_number VARCHAR2(15),
  valid_upto DATE,
  renewal_pending VARCHAR2(20),
  approval_sought VARCHAR2(100),
  remove_image_ids VARCHAR2(500),
  reason VARCHAR2(1000 CHAR),
  summary VARCHAR2(1000 CHAR),
  base_version NUMBER,
  row_version NUMBER DEFAULT 0 NOT NULL,
  created_by VARCHAR2(50) NOT NULL,
  checked_by VARCHAR2(50),
  checker_comment VARCHAR2(1000 CHAR),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  submitted_at TIMESTAMP,
  decided_at TIMESTAMP,
  CONSTRAINT chk_staging_inventory CHECK (unsold_inventory IS NULL OR total_inventory IS NULL OR unsold_inventory <= total_inventory)
)]');
  ddl('CREATE INDEX idx_staging_project ON project_staging(project_id, status)');
  ddl('CREATE INDEX idx_staging_status ON project_staging(status, request_type)');
  ddl(q'[CREATE UNIQUE INDEX ux_staging_one_open ON project_staging (CASE WHEN status IN ('DRAFT','PENDING_APPROVAL','NEEDS_CORRECTION') THEN project_id END)]');

  -- 4. photos belong to a live project OR to staging
  ddl('ALTER TABLE project_images MODIFY (project_id NULL)');
  SELECT COUNT(*) INTO n FROM user_tab_columns WHERE table_name = 'PROJECT_IMAGES' AND column_name = 'STAGING_ID';
  IF n = 0 THEN
    ddl('ALTER TABLE project_images ADD (staging_id NUMBER)');
    ddl('ALTER TABLE project_images ADD CONSTRAINT fk_project_images_staging FOREIGN KEY (staging_id) REFERENCES project_staging(id) ON DELETE CASCADE');
    ddl('CREATE INDEX idx_img_staging ON project_images(staging_id)');
  END IF;

  -- 5. move every unapproved project into staging as a CREATE request
  ddl(q'[INSERT INTO project_staging (project_id, request_type, status, zone_name, branch_name, state_name, city_name, project_name, rera_no, property_id, type_of_unit, approval_date, total_inventory, unsold_inventory, inventory_as_on_date, amenities, start_date, completion_date, apt_per_floor, no_of_towers, total_project_area, carpet_min, carpet_max, buildup_min, buildup_max, dist_railway, dist_airport, avg_rate, budget_min, budget_max, builder_name, project_address, pin_code, promoter1, promoter2, promoter3, promoter4, promoter5, sales_exec_name, sales_mobile, sales_email, website, builder_rating, builder_bg, branch_head_name, branch_head_number, rel_exec_name, rel_exec_number, valid_upto, renewal_pending, approval_sought, created_by, checked_by, checker_comment, created_at, updated_at, submitted_at)
        SELECT id, 'CREATE', status, zone_name, branch_name, state_name, city_name, project_name, rera_no, property_id, type_of_unit, approval_date, total_inventory, unsold_inventory, inventory_as_on_date, amenities, start_date, completion_date, apt_per_floor, no_of_towers, total_project_area, carpet_min, carpet_max, buildup_min, buildup_max, dist_railway, dist_airport, avg_rate, budget_min, budget_max, builder_name, project_address, pin_code, promoter1, promoter2, promoter3, promoter4, promoter5, sales_exec_name, sales_mobile, sales_email, website, builder_rating, builder_bg, branch_head_name, branch_head_number, rel_exec_name, rel_exec_number, valid_upto, renewal_pending, approval_sought, NVL(created_by, 'unknown'), checked_by, checker_comment, created_at, updated_at,
               CASE WHEN status = 'PENDING_APPROVAL' THEN updated_at END
          FROM projects WHERE status NOT IN ('APPROVED', 'DELETED')]');
  ddl(q'[UPDATE project_images i SET staging_id = (SELECT s.id FROM project_staging s WHERE s.project_id = i.project_id AND s.request_type = 'CREATE'),
                                       project_id = NULL
          WHERE i.project_id IN (SELECT project_id FROM project_staging WHERE request_type = 'CREATE')]');
  ddl(q'[DELETE FROM projects WHERE status NOT IN ('APPROVED', 'DELETED')]');

  -- the check constraint last (all rows are consistent now)
  ddl('ALTER TABLE project_images ADD CONSTRAINT chk_image_owner CHECK ((project_id IS NULL AND staging_id IS NOT NULL) OR (project_id IS NOT NULL AND staging_id IS NULL))');
  COMMIT;
  DBMS_OUTPUT.PUT_LINE('Staging model installed; unapproved projects moved to PROJECT_STAGING');
END;

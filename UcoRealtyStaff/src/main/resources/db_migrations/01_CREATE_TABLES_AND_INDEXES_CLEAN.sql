  CASE WHEN status IN ('DRAFT','PENDING_APPROVAL','NEEDS_CORRECTION') THEN project_id END);

CREATE TABLE realty_project_images (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id VARCHAR2(20),
  staging_id NUMBER,
  file_name VARCHAR2(255),
  mime_type VARCHAR2(100),
  file_size NUMBER(19,0),
  file_data BLOB,
  file_path VARCHAR2(500) NOT NULL,
  is_verified NUMBER(1) DEFAULT 0 NOT NULL,
  uploaded_by VARCHAR2(50),
  uploaded_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_realty_img_project FOREIGN KEY (project_id) REFERENCES realty_projects(id) ON DELETE CASCADE,
  CONSTRAINT fk_realty_img_staging FOREIGN KEY (staging_id) REFERENCES realty_project_staging(id) ON DELETE CASCADE,
  CONSTRAINT chk_realty_image_owner CHECK ((project_id IS NULL AND staging_id IS NOT NULL) OR (project_id IS NOT NULL AND staging_id IS NULL))
)
LOB (file_data) STORE AS SECUREFILE (
  ENABLE STORAGE IN ROW
  CHUNK 8192
  RETENTION AUTO
  CACHE
);

CREATE TABLE realty_project_attachments (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id VARCHAR2(20),
  staging_id NUMBER,
  file_name VARCHAR2(255 CHAR) NOT NULL,
  doc_type VARCHAR2(20) DEFAULT 'OTHER' NOT NULL,
  doc_title VARCHAR2(100 CHAR),
  mime_type VARCHAR2(100),
  file_size NUMBER(19,0),
  file_data BLOB,
  uploaded_by VARCHAR2(50),
  uploaded_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_realty_att_project FOREIGN KEY (project_id) REFERENCES realty_projects(id) ON DELETE CASCADE,
  CONSTRAINT fk_realty_att_staging FOREIGN KEY (staging_id) REFERENCES realty_project_staging(id) ON DELETE CASCADE,
  CONSTRAINT chk_realty_att_owner CHECK ((project_id IS NULL AND staging_id IS NOT NULL) OR (project_id IS NOT NULL AND staging_id IS NULL)),
  CONSTRAINT chk_realty_att_doctype CHECK (doc_type IN ('BROCHURE','FLOOR_PLAN','RERA','OTHER'))
)
LOB (file_data) STORE AS SECUREFILE (
  ENABLE STORAGE IN ROW
  CHUNK 8192
  RETENTION AUTO
  CACHE
);

CREATE TABLE realty_audit_log (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type VARCHAR2(50) NOT NULL,
  entity_id VARCHAR2(100) NOT NULL,
  action VARCHAR2(50) NOT NULL,
  by_user VARCHAR2(50),
  old_val VARCHAR2(1000 CHAR),
  new_val VARCHAR2(1000 CHAR),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE realty_login_audit (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR2(100),
  ip_address VARCHAR2(50),
  success NUMBER(1) NOT NULL,
  remarks VARCHAR2(500 CHAR),
  login_time TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

